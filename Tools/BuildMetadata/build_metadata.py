"""Deterministic build identity; standard library only, no runtime/service access."""
import argparse
import hashlib
import json
import plistlib
import re
import subprocess
from pathlib import Path


def git(root, *args):
    return subprocess.check_output(
        ["git", "-C", str(root), *args], text=True, stderr=subprocess.PIPE
    ).strip()


def metadata(root):
    info = plistlib.loads((root / "Resources/Info.plist").read_bytes())
    identity = (root / "Sources/RemoteCompletionCore/CompletionIdentity.h").read_text()

    def constant(name):
        match = re.search(r'^#define ' + name + r' "([A-Za-z0-9._/-]+)"$', identity, re.M)
        if not match:
            raise ValueError("Missing or invalid identity constant: " + name)
        return match.group(1)

    protocol = root / "Sources/RemoteCompletionCore/RemoteCompletionProtocol.m"
    result = {
        "SchemaVersion": 1,
        "ProductVersion": info["CFBundleShortVersionString"],
        "BuildNumber": info["CFBundleVersion"],
        "GitCommit": git(root, "rev-parse", "--verify", "HEAD"),
        "WorktreeDirty": bool(git(root, "status", "--porcelain", "--untracked-files=normal")),
        "PromptVersion": constant("CPA_PROMPT_VERSION"),
        "PromptSourceSHA256": hashlib.sha256(protocol.read_bytes()).hexdigest(),
        "DefaultLocalModel": constant("CPA_DEFAULT_LOCAL_MODEL"),
    }
    return info, result


def write_if_changed(path, data):
    if path.exists() and path.read_bytes() == data:
        return
    path.parent.mkdir(parents=True, exist_ok=True)
    temporary = path.with_name(path.name + ".tmp")
    temporary.write_bytes(data)
    temporary.replace(path)


def generate(root, output):
    info, identity = metadata(root)
    suffix = "+dirty" if identity["WorktreeDirty"] else ""
    label = f'{identity["ProductVersion"]} ({identity["BuildNumber"]}) · {identity["GitCommit"][:12]}{suffix}'
    summary = (
        f'version={identity["ProductVersion"]} build={identity["BuildNumber"]} '
        f'commit={identity["GitCommit"]} dirty={int(identity["WorktreeDirty"])} '
        f'prompt={identity["PromptVersion"]} promptSHA256={identity["PromptSourceSHA256"]} '
        f'model={identity["DefaultLocalModel"]}'
    )
    defines = {
        "CPA_BUILD_LABEL": label,
        "CPA_BUILD_SUMMARY": summary,
        "CPA_BUILD_METADATA_JSON": json.dumps(identity, sort_keys=True, ensure_ascii=False),
    }
    header = "// Generated by Tools/BuildMetadata/build_metadata.py. Do not edit.\n#pragma once\n"
    for key, value in defines.items():
        header += f"#define {key} {json.dumps(value, ensure_ascii=False)}\n"
    info["CPABuildMetadata"] = identity
    write_if_changed(output / "Info.plist", plistlib.dumps(info, sort_keys=True))
    write_if_changed(output / "CPABuildMetadata.h", header.encode())
    return identity


def inspect_bundle(bundle):
    info = plistlib.loads((bundle / "Contents/Info.plist").read_bytes())
    executable = bundle / "Contents/MacOS/CodexPromptAssistantPOC"
    return {
        "Bundle": str(bundle.resolve()),
        "ProductVersion": info.get("CFBundleShortVersionString", "unknown"),
        "BuildMetadata": info.get("CPABuildMetadata", {"GitCommit": "unknown (legacy build)"}),
        "ExecutableSHA256": hashlib.sha256(executable.read_bytes()).hexdigest(),
        "Scope": "on-disk bundle only; running identity requires its launch log",
    }


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", type=Path, default=Path(__file__).resolve().parents[2])
    parser.add_argument("--output", type=Path)
    parser.add_argument("--inspect", type=Path, help="Read only; never execute the inspected bundle")
    args = parser.parse_args()
    try:
        if args.inspect:
            print(json.dumps(inspect_bundle(args.inspect), ensure_ascii=False, indent=2))
        elif args.output:
            generate(args.root, args.output)
        else:
            parser.error("choose --output or --inspect")
    except (OSError, ValueError, KeyError, plistlib.InvalidFileException, subprocess.CalledProcessError) as error:
        parser.exit(1, f"Build metadata failed: {error}\n")


if __name__ == "__main__":
    main()
